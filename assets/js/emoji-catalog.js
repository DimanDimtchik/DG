  function allChars() {
    var out = [];
    var seen = Object.create(null);
    GROUPS.forEach(function (g) {
      (g.chars || []).forEach(function (c) {
        if (!seen[c]) {
          seen[c] = true;
          out.push(c);
        }
      });
    });
    return out;
  }

  function search(query) {
    var q = String(query || '').trim().toLowerCase();
    if (!q) {
      return GROUPS;
    }
    // Zeichen-Suche: Treffer in allen Gruppen filtern
    return GROUPS.map(function (g) {
      return {
        id: g.id,
        label: g.label,
        chars: (g.chars || []).filter(function (c) {
          return c.indexOf(q) !== -1 || g.label.toLowerCase().indexOf(q) !== -1;
        }),
      };
    }).filter(function (g) {
      return g.chars.length > 0;
    });
  }

  return {
    groups: GROUPS,
    allChars: allChars,
    search: search,
    count: allChars().length,
  };
