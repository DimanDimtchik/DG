function lucideExtractPaths(string $content): string
{
    $parts = [];
    if (preg_match_all('/\[\s*"(path|circle|rect|line|polyline|polygon|ellipse)"\s*,\s*\{([^}]*)\}\s*\]/', $content, $matches, PREG_SET_ORDER)) {
        foreach ($matches as $match) {
            $tag = $match[1];
            $attrs = $match[2];
            if ($tag === 'path' && preg_match('/d:\s*"([^"]+)"/', $attrs, $d)) {
                $parts[] = '<path d="' . $d[1] . '"/>';
            } elseif ($tag === 'circle' && preg_match('/cx:\s*"([^"]+)"[^}]*cy:\s*"([^"]+)"[^}]*r:\s*"([^"]+)"/', $attrs, $c)) {
                $parts[] = '<circle cx="' . $c[1] . '" cy="' . $c[2] . '" r="' . $c[3] . '"/>';
            } elseif ($tag === 'rect' && preg_match_all('/(\w+):\s*"([^"]+)"/', $attrs, $ra, PREG_SET_ORDER)) {
                $map = [];
                foreach ($ra as $a) {
                    $map[$a[1]] = $a[2];
                }
                $rect = '<rect';
                foreach (['x', 'y', 'width', 'height', 'rx', 'ry'] as $k) {
                    if (isset($map[$k])) {
                        $rect .= ' ' . $k . '="' . $map[$k] . '"';
                    }
                }
                $parts[] = $rect . '/>';
            } elseif ($tag === 'line' && preg_match_all('/(\w+):\s*"([^"]+)"/', $attrs, $la, PREG_SET_ORDER)) {
                $map = [];
                foreach ($la as $a) {
                    $map[$a[1]] = $a[2];
                }
                if (isset($map['x1'], $map['y1'], $map['x2'], $map['y2'])) {
                    $parts[] = '<line x1="' . $map['x1'] . '" y1="' . $map['y1'] . '" x2="' . $map['x2'] . '" y2="' . $map['y2'] . '"/>';
                }
            }
        }
    }

    return implode('', $parts);
}

function lucideHumanLabel(string $id): string
{
    $words = explode('-', $id);
    $words = array_map(static fn (string $w): string => mb_convert_case($w, MB_CASE_TITLE, 'UTF-8'), $words);

    return implode(' ', $words);
}

/** @return list<string> */
function lucideTags(string $id, string $label): array
{
    $tags = array_merge(explode('-', $id), preg_split('/\s+\/?\s*/', mb_strtolower($label)) ?: []);
    $tags = array_values(array_unique(array_filter(array_map('trim', $tags))));

    return $tags;
}
