<?php
declare(strict_types=1);

/**
 * Baut den Kern-Katalog aus storage/media/training (alle *.meta.json rekursiv).
 * Nur Einträge mit Titel — Export-Metas ohne title entfallen.
 *
 * php bin/academy-build-training-catalog.php
 */

define('DG_ROOT', dirname(__DIR__));

$root = DG_ROOT . '/storage/media/training';
$outFile = DG_ROOT . '/src/Academy/data/training-catalog.php';

if (!is_dir($root)) {
    fwrite(STDERR, "Missing {$root}\n");
    exit(1);
}

$items = [];
$iterator = new RecursiveIteratorIterator(
    new RecursiveDirectoryIterator($root, FilesystemIterator::SKIP_DOTS)
);

foreach ($iterator as $file) {
    if (!$file instanceof SplFileInfo || !$file->isFile()) {
        continue;
    }
    if (!str_ends_with(strtolower($file->getFilename()), '.meta.json')) {
        continue;
    }

    $abs = $file->getPathname();
    $relMeta = str_replace('\\', '/', substr($abs, strlen($root) + 1));
    $dir = dirname($relMeta);
    if ($dir === '.') {
        $dir = '';
    }
    $slug = basename($relMeta, '.meta.json');
    if ($slug === '' || str_ends_with($slug, '-export') || str_contains($slug, '-export.')) {
        continue;
    }
    if (preg_match('/-export$/i', $slug) === 1) {
        continue;
    }

    $raw = json_decode((string) file_get_contents($abs), true);
    if (!is_array($raw)) {
        continue;
    }
    $title = trim((string) ($raw['title'] ?? ''));
    if ($title === '') {
        continue;
    }

    $duration = (int) round((float) ($raw['duration_sec'] ?? 0));
    $mp4Rel = 'media/training/' . ($dir !== '' ? $dir . '/' : '') . $slug . '.mp4';
    $vttRel = 'media/training/' . ($dir !== '' ? $dir . '/' : '') . $slug . '.vtt';

    $items[] = [
        'key' => ($dir !== '' ? $dir . '/' : '') . $slug,
        'folder' => $dir,
        'slug' => $slug,
        'title' => $title,
        'duration_sec' => max(0, $duration),
        'video_path' => $mp4Rel,
        'subtitle_vtt_path' => $vttRel,
        'locale' => (string) ($raw['locale'] ?? 'de'),
        'voice' => (string) ($raw['voice'] ?? ''),
    ];
}

usort($items, static fn (array $a, array $b): int => strcasecmp($a['title'], $b['title']));

$dirOut = dirname($outFile);
if (!is_dir($dirOut) && !mkdir($dirOut, 0755, true) && !is_dir($dirOut)) {
    fwrite(STDERR, "Cannot create {$dirOut}\n");
    exit(1);
}

$export = var_export($items, true);
$content = "<?php\ndeclare(strict_types=1);\n\n"
    . "/** Auto-generated by bin/academy-build-training-catalog.php — do not edit. */\n"
    . 'return ' . $export . ";\n";

file_put_contents($outFile, $content);
echo 'Wrote ' . count($items) . " entries -> {$outFile}\n";
